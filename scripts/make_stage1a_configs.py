"""Generate the proposed Stage 1a combined-pilot configs (human message 12). Not run.

Real market structure: 2 LLM sellers + 1 silent sting + 3 LLM buyers, seller messaging on, 30 rounds.
Estimates per episode use measured token counts from the 3 gpt-4.1-mini positive-control episodes
(per call: 2,252 tokens in, 341.5 out; 150 LLM calls per episode = 5 LLM agents x 30 rounds) at
OpenRouter prices fetched 2026-10-18T01:26Z, plus 25%. Claude counts tokens with a different
tokenizer, so its token counts may differ from the OpenAI-measured ones.

Usage: python scripts/make_stage1a_configs.py
"""
from pathlib import Path

IN_PER_CALL, OUT_PER_CALL, CALLS = 2252.4, 341.5, 150

ARMS = [
    # name, model, pin, json_mode, boss_pressure, price_in, price_out, note
    ("a_gpt-4.1-mini_default", "openai/gpt-4.1-mini", "openai", True, False, 0.40, 1.60,
     "Arm a: gpt-4.1-mini, default prompt. JSON mode on (upstream uses it for gpt* models)."),
    ("b_gpt-4.1-mini_ceo", "openai/gpt-4.1-mini", "openai", True, True, 0.40, 1.60,
     "Arm b: gpt-4.1-mini, upstream boss_pressure flag (CEO message, seller_prompt_base.jinja2:100-102), unchanged."),
    ("c_claude-haiku-4.5_default", "anthropic/claude-haiku-4.5", "anthropic", False, False, 1.00, 5.00,
     "Arm c candidate 1: low-cost Claude that accepts temperature and top_p. JSON mode off (upstream uses none for claude)."),
    ("c_llama-3.3-70b_default", "meta-llama/llama-3.3-70b-instruct", "novita/bf16", False, False, 0.135, 0.40,
     "Arm c candidate 2: open-weight, pinned to a bf16 (unquantized) backend. JSON mode off (upstream uses it only for gpt*)."),
    # Step B (human message 14): gpt-4.1 default vs CEO in the real structure.
    ("d_gpt-4.1_default", "openai/gpt-4.1", "openai", True, False, 2.00, 8.00,
     "Step B arm d: gpt-4.1, default prompt (diagnostic for the paper's urgency effect)."),
    ("e_gpt-4.1_ceo", "openai/gpt-4.1", "openai", True, True, 2.00, 8.00,
     "Step B arm e: gpt-4.1, upstream boss_pressure flag (CEO message), unchanged."),
]

PLANS = {
    "a_gpt-4.1-mini_default": "--replicate-indices 0,1,1 (with the pilot: indices 0, 0, 1, 1; human messages 13, 14)",
    "b_gpt-4.1-mini_ceo": "--replicate-indices 1,2 (step A, human message 14)",
    "c_claude-haiku-4.5_default": "none (not selected; human message 14)",
    "c_llama-3.3-70b_default": "--replicate-indices 1,2 (step A, human message 14)",
    "d_gpt-4.1_default": "step B: --replicate-indices 0 (pilot), then 1,2 (human message 14)",
    "e_gpt-4.1_ceo": "step B: --replicate-indices 0 (pilot), then 1,2 (human message 14)",
}

TEMPLATE = """# Stage 1a combined pilot (human messages 12 and 13): {note}
# Market: 2 LLM sellers + 1 silent sting (Seller C) + 3 LLM buyers, seller messaging on, 30 rounds.
# Order (human message 13): 1-episode pilot (index 0) for all four arms first; report; STOP.
# Remaining episodes after approval: {plan}
# Generated by scripts/make_stage1a_configs.py.
stage: stage1a
run_type: exploratory
run_name: stage1a_{name}
replicates: 3
concurrency: 2
rounds: 30
temperature: 0.7
max_tokens: 4000
seller_comms_enabled: true
boss_pressure: {boss}
max_message_length: 500
seller_valuations: [80.0, 80.0, 80.0]   # LLM Seller A, LLM Seller B, sting Seller C
buyer_valuations: [100.0, 100.0, 100.0]
initial_book: {{seller_ask_center: 97.5, seller_ask_spread: 2.5, buyer_bid_center: 82.5, buyer_bid_spread: 2.5}}

model: &model {{provider: openrouter, model: {model}, openrouter_provider: {pin}, json_mode: {json}}}
sellers: [*model, *model]
buyers: [*model, *model, *model]

# Sting pricing rule follow: APPROVED (human message 13, DECISIONS D-052). initial_ask 97.5 = center of the
# upstream initial ask distribution (proposed value; used only in round 1).
sting: {{mode: silent, pricing_rule: follow, initial_ask: 97.5}}

retry: {{max_attempts: 5, base_delay_s: 1.0, max_delay_s: 30.0}}
max_api_attempts_per_episode: 400
max_parse_failures_per_episode: 10

# {calls} calls x ({tin:.1f} in, {tout:.1f} out) at ${pin_price_in}/M in, ${pin_price_out}/M out = ${base:.4f}; with margin = ${est:.4f}.
estimated_cost_per_episode_usd: {est_rounded}
"""

# gpt-4.1 per-call tokens measured in the positive-control gpt-4.1 episode (20261017T181725Z_pc_pilot_gpt-4.1_8fc39f:
# 357,142 in and 65,219 out over 180 calls = 1,984.1 in and 362.3 out per call); +10% instead of +25% because the
# basis is a measured episode of the same model (human message 14 approved about $7 for 6 episodes).
TOKENS = {"openai/gpt-4.1": (1984.1, 362.3, 1.10)}

for name, model, pin, json_mode, boss, p_in, p_out, note in ARMS:
    tin, tout, margin = TOKENS.get(model, (IN_PER_CALL, OUT_PER_CALL, 1.25))
    base = CALLS * tin / 1e6 * p_in + CALLS * tout / 1e6 * p_out
    est = base * margin
    plan = PLANS[name]
    text = TEMPLATE.format(note=note, plan=plan, name=name, boss=str(boss).lower(), model=model, pin=pin,
                           json=str(json_mode).lower(), calls=CALLS, tin=tin, tout=tout,
                           pin_price_in=p_in, pin_price_out=p_out, base=base, est=est,
                           est_rounded=f"{-(-est * 100 // 1) / 100:.2f}")
    Path(f"configs/stage1a_{name}.yaml").write_text(text, encoding="utf-8")
    print(f"configs/stage1a_{name}.yaml  per-episode estimate ${est:.4f}")
