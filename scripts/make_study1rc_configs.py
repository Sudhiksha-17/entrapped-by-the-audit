"""Generate the Study 1R-C configs (human message 79; prereg_study1r/AMENDMENT_1RC.md). Nothing is run.

Each arm config is the frozen Study 1R Silent config of its cell (configs/study1r/<cell>_silent.yaml) with only these
changes: stage, run_name, budget group and cap, the per-episode cost estimate, and, in Silent-floor, `silent_floor:
true` inside sting.x_rule (sting.study1rc.StingSeller1RC: ask = max(X, follow) from round 10, no posts).

Costs: measured mean cost per completed Silent episode in Study 1R (both campaigns, probe included): mini-low $0.2230
(33 episodes), 4.1-high $0.9955 (66 episodes: main study and Study 1R-A); x 1.10 margin in the configs, as for Study 1R.
Cap = planned total x 1.15, as for Study 1R and Study 1R-A.

Usage: python scripts/make_study1rc_configs.py
"""
from __future__ import annotations

import copy
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "configs" / "study1r_addon_C"
MEASURED = {"mini-low": 0.2230, "4.1-high": 0.9955}
MARGIN, CAP_FACTOR, N = 1.10, 1.15, 33
CELLS = ("mini-low", "4.1-high")
ARMS = ("silent_floor", "silent")
GROUP = "study1r_addon_C"


def per_episode(cell: str) -> float:
    return round(MEASURED[cell] * MARGIN, 4)


def planned() -> dict:
    total = sum(per_episode(c) * N * len(ARMS) for c in CELLS)
    return {"episodes": N * len(ARMS) * len(CELLS), "planned_usd": round(total, 2), "cap_usd": round(total * CAP_FACTOR, 2),
            "per_episode": {c: per_episode(c) for c in CELLS}}


def arm_cfg(cell: str, arm: str, cap: float) -> dict:
    cfg = yaml.safe_load((REPO / "configs" / "study1r" / f"{cell}_silent.yaml").read_text(encoding="utf-8"))
    cfg = copy.deepcopy(cfg)
    cfg["stage"] = GROUP
    cfg["run_name"] = f"{GROUP}_{cell}_{arm}"
    cfg["estimated_cost_per_episode_usd"] = per_episode(cell)
    cfg["budget"] = {"group": GROUP, "cap_usd": cap}
    assert cfg["sting"]["condition"] == "silent" and "competitive" not in cfg["sting"]
    if arm == "silent_floor":
        cfg["sting"]["x_rule"] = dict(cfg["sting"]["x_rule"], silent_floor=True)
    return cfg


def main() -> None:
    plan = planned()
    OUT.mkdir(parents=True, exist_ok=True)
    arms = []
    for cell in CELLS:
        for arm in ARMS:
            name = f"{cell}_{arm}"
            (OUT / f"{name}.yaml").write_text(
                "# Study 1R-C pricing-control arm (human message 79; prereg_study1r/AMENDMENT_1RC.md). Generated by "
                "scripts/make_study1rc_configs.py. Runs only through `python -m sting.study1rc run`.\n"
                + yaml.safe_dump(arm_cfg(cell, arm, plan["cap_usd"]), sort_keys=False), encoding="utf-8")
            arms.append({"name": name, "cell": cell, "arm": arm, "config": f"configs/study1r_addon_C/{name}.yaml",
                         "indices": list(range(N))})
    campaign = {"name": GROUP, "stage": GROUP, "run_type": "confirmatory", "prereg_dir": "prereg_study1r",
                "freeze_lock": "prereg_study1r/FROZEN_1RC.json", "n_per_arm": N, "indices": list(range(N)),
                "concurrency": 4, "order_seed": 20261025, "max_replacement_passes": 3,
                "budget": {"group": GROUP, "cap_usd": plan["cap_usd"]}, "arms": arms}
    (OUT / "campaign.yaml").write_text("# Study 1R-C campaign (pricing control). Runs only through "
                                       "`python -m sting.study1rc run`; NOT RUN until approved and frozen.\n"
                                       + yaml.safe_dump(campaign, sort_keys=False), encoding="utf-8")
    print(plan)


if __name__ == "__main__":
    main()
