"""Study 1R-D Cell B provider speed test configs (human message 88; exploratory; indices 2000+; never confirmatory).

Each config is configs/study1r_addon_D/screening/qwen_silent.yaml (Study 1R mini-low Silent design, all five LLM agents
on qwen/qwen3-235b-a22b-2507, same temperature, max_tokens and settings) with only the pinned OpenRouter provider, the
run name, the budget group (study1r_addon_D_speedtest, cap $3) and replicates (1) changed. DeepInfra is excluded
(human message 88: Cell B is not resumed on DeepInfra).

Usage: python scripts/make_study1rd_speedtest_configs.py
"""
from __future__ import annotations

import copy
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "configs" / "study1r_addon_D" / "screening" / "qwen_silent.yaml"
OUT = REPO / "configs" / "study1r_addon_D" / "speedtest"
# OpenRouter endpoints for qwen/qwen3-235b-a22b-2507 with structured output, 2026-10-25 19:14 local (DeepInfra excluded)
PROVIDERS = {"parasail": "parasail", "venice": "venice", "gmicloud": "gmicloud", "vertex": "google-vertex"}


def main() -> None:
    base = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    for key, slug in PROVIDERS.items():
        cfg = copy.deepcopy(base)
        for agent in cfg["sellers"] + cfg["buyers"]:
            assert agent["model"] == "qwen/qwen3-235b-a22b-2507"
            agent["openrouter_provider"] = slug
        cfg.update(stage="study1r_addon_D_speedtest", run_name=f"s1rd_spd_{key}", replicates=1,
                   budget={"group": "study1r_addon_D_speedtest", "cap_usd": 3.0})
        (OUT / f"{key}_silent.yaml").write_text(
            "# Study 1R-D Cell B provider speed test (human message 88; exploratory; index 2000+). Generated by "
            "scripts/make_study1rd_speedtest_configs.py.\n" + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        print(key, slug)


if __name__ == "__main__":
    main()
