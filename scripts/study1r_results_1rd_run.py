"""Run the frozen Study 1R-D analysis (scripts/study1r_results_1rd.py) for Cell A and write
results/study1r/RESULTS_1RD.md (human message 89). No API calls; no frozen file changed.

- Cell A: every finished Study 1R-D campaign log (runs/study1r_addon_D/_campaigns), copied with only the two mini-low
  arms, so the first Cell B (DeepInfra; stopped and excluded, I-066) is not passed to the analysis.
- Cell B is not analysed (incomplete; I-066, I-070; human message 88).
- Stability input: the Study 1R-C campaign logs (main repository runs, absolute run_dir paths in the logs).
The expected excluded set passed to the wrapper (--expect-excluded) is every replicate in those logs whose status is not
"completed", listed from the status files before the analysis; the wrapper stops if its own exclusion set differs.

Usage: python scripts/study1r_results_1rd_run.py <rc_campaign_logs_dir>
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PY = sys.executable
CELL_A_ARMS = {"mini-low_offer_floor", "mini-low_silent_floor"}


def finished(camp_dir: Path) -> list[Path]:
    return sorted(p / "campaign.json" for p in camp_dir.iterdir() if p.is_dir() and (p / "campaign.json").is_file()
                  and "finished_utc" in (p / "campaign.json").read_text(encoding="utf-8"))


def not_completed(logs: list[Path]) -> list[str]:
    out = []
    for log in logs:
        for info in json.loads(log.read_text(encoding="utf-8"))["arms"].values():
            for rep in Path(info["run_dir"]).iterdir():
                st = rep / "status.json"
                if rep.is_dir() and st.is_file() and json.loads(st.read_text(encoding="utf-8"))["status"] != "completed":
                    out.append(rep.name)
    return sorted(set(out))


def run(out_dir: Path, campaign_yaml: str, logs: list[Path], rc_yaml: Path, rc_logs: list[Path]) -> str:
    cmd = [PY, "scripts/study1r_results_1rd.py", str(out_dir), "--campaign-yaml", campaign_yaml,
           "--logs", ",".join(map(str, logs)), "--expect-excluded", ",".join(not_completed(logs)),
           "--rc-yaml", str(rc_yaml), "--rc-logs", ",".join(map(str, rc_logs)),
           "--rc-expect-excluded", ",".join(not_completed(rc_logs))]
    r = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"analysis failed for {campaign_yaml}:\n{r.stdout[-2000:]}\n{r.stderr[-3000:]}")
    return (out_dir / "RESULTS_1RD.md").read_text(encoding="utf-8")


def main() -> None:
    rc_dir = Path(sys.argv[1])
    rc_logs = finished(rc_dir)
    rc_yaml = REPO / "configs" / "study1r_addon_C" / "campaign.yaml"
    with tempfile.TemporaryDirectory(prefix="s1rd_a_") as tmp:
        a_logs = []
        for i, log in enumerate(finished(REPO / "runs" / "study1r_addon_D" / "_campaigns")):
            d = json.loads(log.read_text(encoding="utf-8"))
            d["arms"] = {k: v for k, v in d["arms"].items() if k in CELL_A_ARMS}
            if d["arms"]:
                p = Path(tmp) / f"c{i:02d}.json"
                p.write_text(json.dumps(d, indent=2), encoding="utf-8")
                a_logs.append(p)
        md_a = run(REPO / "results" / "study1r_addon_D" / "analysis_cell_a", "configs/study1r_addon_D/campaign.yaml",
                   a_logs, rc_yaml, rc_logs)
    # Cell B is not analysed (human message 88): the first Cell B (DeepInfra) was stopped and excluded (I-066); the fresh
    # Cell B (Parasail) was stopped by the preregistered failure-rate condition and cannot finish by the 02:00 cutoff
    # (I-070), so it is reported as incomplete.
    b_logs = finished(REPO / "runs" / "study1r_addon_D_b2" / "_campaigns")
    head = ["# Study 1R-D results", "",
            "Preregistered add-on (prereg_study1r/AMENDMENT_1RD.md and addendum 1; lock FROZEN_1RD.json). Facts only. "
            "Generated by `scripts/study1r_results_1rd_run.py`, which runs the frozen `scripts/study1r_results_1rd.py` "
            "for Cell A (the mini-low arms of the Study 1R-D campaign logs) through the completed-episodes wrapper. "
            "**Cell B is not analysed:** the first Cell B (DeepInfra) was stopped and is excluded (I-066); the fresh "
            "Cell B (Parasail) was stopped by the preregistered failure-rate condition after OpenRouter's shared limit "
            "of 18 requests per minute for the model, and is reported as incomplete (I-070; human message 88). The "
            "frozen script reports the Cell B sections as skipped (arm missing).", "",
            f"Campaign logs analysed: Cell A {len(a_logs)}; Study 1R-C (stability) {len(rc_logs)}. Fresh Cell B "
            f"campaign logs on disk, not analysed: {len(b_logs)}.", ""]
    demote = lambda md: ["#" + l if l.startswith("## ") else l for l in md.split("\n")[1:]]  # noqa: E731
    body = ["## Cell A (mini-low, gpt-4.1-mini)", ""] + demote(md_a) + \
           ["", "## Cell B", "", "Not analysed (incomplete); see I-066 and I-070."]
    out = REPO / "results" / "study1r" / "RESULTS_1RD.md"
    out.write_text("\n".join(head + body) + "\n", encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
