"""ISSUES I-021: read-only extraction from an existing smoke run log. No API calls.

For each round and seller: the ask, sentences in the seller's reasoning, memory,
scratchpad and message that mention cost, price level, profit or loss, and per-trade
seller profit (trade price minus the seller's configured cost). Also counts how many
rendered prompts state each agent's cost or value.

Usage:
    python scripts/i021_extract.py runs/smoke/<run_id> results/i021/smoke_extract.md
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

FIELDS = ["reflection", "plan_for_this_hour", "new_memory", "plan_for_message", "message_to_sellers",
          "scratch_pad_update"]
PATTERN = re.compile(r"\bcost|\$?\b80(\.0+)?\b|profit|loss|break[- ]?even|margin|below|competitive|equilibrium",
                     re.IGNORECASE)


def blocks(md_text: str, kind: str) -> dict[int, str]:
    """Map round -> fenced block content for '## Prompt: Round N' or '## Response: Round N' sections."""
    out = {}
    for m in re.finditer(rf"## {kind}: Round (\d+) - [^\n]*\n(`{{4,6}})(?:json)?\n(.*?)\n\2", md_text, flags=re.S):
        out[int(m.group(1))] = m.group(3)
    return out


def sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+|\n+", text or "") if s.strip()]


def main(run_dir: Path, out_path: Path) -> None:
    rep = next(p for p in sorted(run_dir.iterdir()) if p.is_dir())
    setup = json.loads((rep / "market_setup.json").read_text(encoding="utf-8"))
    logs = rep / "upstream_logs"
    rounds = [json.loads(b) for b in re.findall(r"````json\n(.*?)\n````",
                                                (logs / "auction_results.md").read_text(encoding="utf-8"), flags=re.S)]
    lines = [f"# I-021 extraction: {run_dir.name}", "",
             "Generated by `scripts/i021_extract.py` from existing logs. Read-only; no API calls.", ""]

    lines += ["## Cost and value statements in rendered prompts", ""]
    for agent in setup["seller_ids"] + setup["buyer_ids"]:
        prompts = blocks((logs / f"{agent}.md").read_text(encoding="utf-8"), "Prompt")
        cost_line = re.compile(r"Your true (cost|value) per lot of heavy metals is \$[0-9.]+\.")
        found = [r for r, p in prompts.items() if cost_line.search(p)]
        sample = cost_line.search(prompts[min(prompts)]).group(0) if found else "(not found)"
        lines.append(f"- {agent}: statement present in {len(found)} of {len(prompts)} prompts; text: \"{sample}\"")
    lines.append("")

    cost = setup["seller_valuations"]
    lines += ["## Per round", ""]
    for r in rounds:
        n = r["round_number"]
        lines.append(f"### Round {n}")
        lines.append("")
        lines.append("| Seller | Ask | Ask minus cost |")
        lines.append("|---|---|---|")
        for sid in setup["seller_ids"]:
            ask = r["seller_asks"].get(sid)
            lines.append(f"| {sid} | {ask} | {round(ask - cost[sid], 2) if isinstance(ask, (int, float)) else ''} |")
        lines.append("")
        if r["trades"]:
            lines.append("Trades (seller profit = price minus seller cost):")
            for t in r["trades"]:
                lines.append(f"- {t['seller_id']} sold to {t['buyer_id']} at {t['price']}; "
                             f"seller profit {round(t['price'] - cost[t['seller_id']], 2)}")
        else:
            lines.append("Trades: none")
        lines.append("")
        for sid in setup["seller_ids"]:
            resp = blocks((logs / f"{sid}.md").read_text(encoding="utf-8"), "Response").get(n)
            if resp is None:
                continue
            data = json.loads(resp)
            hits = [(f, s) for f in FIELDS for s in sentences(str(data.get(f, ""))) if PATTERN.search(s)]
            lines.append(f"{sid} sentences mentioning cost, price level, profit or loss ({len(hits)}):")
            for f, s in hits:
                lines.append(f"- [{f}] {s}")
            lines.append("")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
