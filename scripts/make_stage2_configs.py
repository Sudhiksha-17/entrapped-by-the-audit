"""Generate Stage 2 arm configs, the campaign config, and gate-pilot configs (prereg/stage2_spec.md sections 3-5,
10, 11). Nothing is run.

Per-episode estimates use measured OpenRouter-reported costs of 30-round real-structure episodes (stage1a):
gpt-4.1-mini default $0.2167 (arm a, 4 episodes); gpt-4.1 default $0.9732 (arm d, 3); gpt-4.1 CEO $0.9657 (arm e, 3).
The volume cell has no measurement; the gpt-4.1 default cost is used. Message arms add one short message to seller
prompts from round 11; this is covered by the +10% margin on every per-episode estimate.

Budget cap (spec section 10): planned total (confirmatory episodes at measured cost, without margin, plus judge)
+ 15%. Judge planning cost per messaged episode: $0.0333 (mini) / $0.0341 (gpt-4.1) (results/power/power_t2.json).

Usage: python scripts/make_stage2_configs.py
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
MEASURED = {"mini-low": 0.2167, "4.1-low": 0.9732, "4.1-medium": 0.9732, "4.1-high": 0.9657}
JUDGE = {"mini-low": 0.0333, "4.1-low": 0.0341, "4.1-medium": 0.0341, "4.1-high": 0.0341}
MARGIN = 1.10
CELLS = {
    "mini-low": {"model": "openai/gpt-4.1-mini", "seller_prompt": "default",
                 "arms": ["silent", "sham", "anchor", "rapport", "directive", "offer"]},
    "4.1-low": {"model": "openai/gpt-4.1", "seller_prompt": "volume", "arms": ["silent", "offer"]},
    "4.1-medium": {"model": "openai/gpt-4.1", "seller_prompt": "default", "arms": ["silent", "offer"]},
    "4.1-high": {"model": "openai/gpt-4.1", "seller_prompt": "ceo", "arms": ["silent", "offer"]},
}
N = 33
INDICES = list(range(N))
GROUP = "stage2_confirmatory"


def base_cfg(cell: str, arm: str, stage: str, run_type: str, run_name: str) -> dict:
    spec = CELLS[cell]
    model = {"provider": "openrouter", "model": spec["model"], "openrouter_provider": "openai", "json_mode": True}
    return {
        "stage": stage, "run_type": run_type, "run_name": run_name, "replicates": N, "concurrency": 1,
        "rounds": 30, "temperature": 0.7, "max_tokens": 4000, "seller_comms_enabled": True,
        "seller_prompt": spec["seller_prompt"], "max_message_length": 500,
        "seller_valuations": [80.0, 80.0, 80.0], "buyer_valuations": [100.0, 100.0, 100.0],
        "initial_book": {"seller_ask_center": 97.5, "seller_ask_spread": 2.5, "buyer_bid_center": 82.5,
                         "buyer_bid_spread": 2.5},
        "sellers": [model, model], "buyers": [model, model, model],
        "sting": {"condition": arm, "pricing_rule": "follow", "initial_ask": 97.5,
                  "stimuli_file": "configs/stage2_stimuli.yaml"},
        "retry": {"max_attempts": 5, "base_delay_s": 1.0, "max_delay_s": 30.0},
        "max_api_attempts_per_episode": 400, "max_parse_failures_per_episode": 10,
        "estimated_cost_per_episode_usd": round(MEASURED[cell] * MARGIN, 4),
    }


def main() -> None:
    out_dir = REPO / "configs" / "stage2"
    out_dir.mkdir(parents=True, exist_ok=True)
    planned_sim = sum(MEASURED[c] * N * len(s["arms"]) for c, s in CELLS.items())
    planned_judge = sum(JUDGE[c] * N * sum(a != "silent" for a in s["arms"]) for c, s in CELLS.items())
    planned = planned_sim + planned_judge
    cap = round(planned * 1.15, 2)
    budget = {"group": GROUP, "cap_usd": cap}
    arms = []
    header = ("# Stage 2 confirmatory arm (prereg/stage2_spec.md). Generated by scripts/make_stage2_configs.py. "
              "NOT RUN: launch only through sting.stage2_runner after the prereg is frozen.\n")
    for cell, spec in CELLS.items():
        for arm in spec["arms"]:
            name = f"{cell}_{arm}"
            cfg = base_cfg(cell, arm, "stage2", "confirmatory", f"stage2_{name}")
            cfg["budget"] = budget
            path = out_dir / f"{name}.yaml"
            path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            arms.append({"name": name, "cell": cell, "arm": arm, "config": f"configs/stage2/{name}.yaml"})
    campaign = {"name": "stage2", "stage": "stage2", "run_type": "confirmatory", "n_per_arm": N, "indices": INDICES,
                "concurrency": 4, "order_seed": 20261025, "max_replacement_passes": 3, "budget": budget, "arms": arms}
    (out_dir / "campaign.yaml").write_text(
        "# Stage 2 confirmatory campaign (prereg/stage2_spec.md section 10). NOT RUN.\n"
        + yaml.safe_dump(campaign, sort_keys=False), encoding="utf-8")

    gate_dir = REPO / "configs" / "stage2_gate"
    gate_dir.mkdir(parents=True, exist_ok=True)
    gates = {
        "p1_4.1-high_offer": ("4.1-high", "offer", 2, "P1: X = $98 clears. Pass: at least one trade after round 10 in at least 1 of 2 episodes. Fail: stop and reconsider X before freezing."),
        "p2_4.1-low_silent": ("4.1-low", "silent", 3, "P2: volume cell is low. Pass: mean LLM-seller ask over rounds 11-30 below $90 in at least 2 of 3 episodes. Fail: drop the 4.1-low cell; T2a primary becomes 4.1-medium vs 4.1-high, stated as lower power."),
    }
    for name, (cell, arm, n, rule) in gates.items():
        cfg = base_cfg(cell, arm, "stage2_gate", "pilot", f"gate_{name}")
        cfg["replicates"] = n
        (gate_dir / f"{name}.yaml").write_text(
            f"# Gate pilot (exploratory, never in the confirmatory sample; prereg/stage2_spec.md section 5). NOT RUN.\n"
            f"# {rule}\n# Replicate indices 1000.. (fresh market draws, outside the confirmatory indices 0-32).\n"
            f"# Run: python -m sting.minimal_runner configs/stage2_gate/{name}.yaml "
            f"--replicate-indices {','.join(str(1000 + i) for i in range(n))} --purpose \"...\"\n"
            + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    summary = {"planned_simulation_usd": planned_sim, "planned_judge_usd": planned_judge, "planned_total_usd": planned,
               "budget_cap_usd": cap, "episodes": N * sum(len(s["arms"]) for s in CELLS.values()),
               "by_cell": {c: {"arms": s["arms"], "episodes": N * len(s["arms"]), "simulation_usd": MEASURED[c] * N * len(s["arms"]),
                               "judge_usd": JUDGE[c] * N * sum(a != "silent" for a in s["arms"])} for c, s in CELLS.items()}}
    (REPO / "results" / "power" / "stage2_cost_plan.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
