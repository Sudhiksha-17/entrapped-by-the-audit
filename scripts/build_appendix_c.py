def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:16]


def verbatim(rel: str, title: str, note: str = "", lang: str = "") -> list[str]:
    p = REPO_ROOT / rel
    text = p.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
    L = [f"### {title}", "", f"Source: `{rel}` (sha256 {sha(p)}...)." + (f" {note}" if note else ""), "",
         FENCE + lang, text, FENCE, ""]
    return L


def section(rel: str, start: str, stop: str | None) -> str:
    text = (REPO_ROOT / rel).read_text(encoding="utf-8").replace("\r\n", "\n")
    i = text.index(start)
    j = text.index(stop, i + len(start)) if stop else len(text)
    return text[i:j].rstrip("\n")


def excerpt(rel: str, start: str, stop: str | None, title: str) -> list[str]:
    p = REPO_ROOT / rel
    return [f"### {title}", "", f"Source: `{rel}` (sha256 {sha(p)}...), from \"{start.strip('# ')}\""
            + (f" up to \"{stop.strip('# ')}\"" if stop else " to the end") + ", verbatim.", "",
            FENCE + "markdown", section(rel, start, stop), FENCE, ""]


def sting_block(rel: str) -> str:
    text = (REPO_ROOT / rel).read_text(encoding="utf-8").replace("\r\n", "\n")
    m = re.search(r"^sting:\n(?:  .*\n|\n)*", text, flags=re.M)
    return m.group(0).rstrip("\n")


def delivered_examples() -> list[str]:
    L = ["### C.2.4 Example delivered messages (Study 1R main study, mini-low, replicate index 0)", "",
         "Read from `sting_log.json` (`messages_sent`, rounds 10-14 shown; the sting posts in rounds 10-29) of the "
         "completed episode with replicate index 0 in each message arm; X is that episode's offered level.", ""]
    for arm in ("sham", "anchor", "offer"):
        reps = sorted(d for d in (REPO_ROOT / "runs" / "study1r").glob(f"*_study1r_mini-low_{arm}_*/*_r000")
                      if d.is_dir() and json.loads((d / "status.json").read_text(encoding="utf-8"))["status"] == "completed")
        rep = reps[0]
        sl = json.loads((rep / "sting_log.json").read_text(encoding="utf-8"))
        x = (sl.get("x") or {}).get("x")
        L += [f"**{arm.capitalize()}** (`{rep.name}`; X = ${x:.2f}):", ""]
        for m in sl["messages_sent"]:
            if m["round"] <= 14:
                L.append(f"- Round {m['round']}: {m['text']}")
        L.append("")
    return L


