"""Generate the fresh Study 1R-D Cell B configs (human message 88; prereg_study1r/AMENDMENT_1RD_ADDENDUM_1.md).
Nothing is run.

Each arm config is the corresponding first-Cell-B config (configs/study1r_addon_D/qwen_<arm>.yaml: same model,
temperature, max_tokens, prompts and settings) with only the pinned OpenRouter provider, stage, run name, budget group
and cap, and the per-episode cost estimate changed. Arms Silent, Silent-floor, Offer-floor; N = 33; indices 0-32.
Cost per episode: the provider's measured speed-test episode cost x 1.10; cap = planned x 1.15.

Usage: python scripts/make_study1rd_b2_configs.py --provider SLUG --key KEY --cost USD_PER_EPISODE
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "configs" / "study1r_addon_D_b2"
GROUP, N, MARGIN, CAP_FACTOR = "study1r_addon_D_b2", 33, 1.10, 1.15
ARMS = ("silent", "silent_floor", "offer_floor")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", required=True)
    ap.add_argument("--key", required=True)
    ap.add_argument("--cost", type=float, required=True)
    a = ap.parse_args()
    per = round(a.cost * MARGIN, 4)
    planned = round(per * N * len(ARMS), 2)
    cap = round(planned * CAP_FACTOR, 2)
    OUT.mkdir(parents=True, exist_ok=True)
    arms = []
    for arm in ARMS:
        cfg = yaml.safe_load((REPO / "configs" / "study1r_addon_D" / f"qwen_{arm}.yaml").read_text(encoding="utf-8"))
        for agent in cfg["sellers"] + cfg["buyers"]:
            agent["openrouter_provider"] = a.provider
        name = f"{a.key}_{arm}"
        cfg.update(stage=GROUP, run_name=f"s1rdb2_{name}", estimated_cost_per_episode_usd=per,
                   budget={"group": GROUP, "cap_usd": cap})
        (OUT / f"{name}.yaml").write_text("# Study 1R-D fresh Cell B arm (human message 88; addendum 1). Generated by "
                                          "scripts/make_study1rd_b2_configs.py. Runs only through "
                                          "`python -m sting.study1rd_b2 run`.\n" + yaml.safe_dump(cfg, sort_keys=False),
                                          encoding="utf-8")
        arms.append({"name": name, "cell": a.key, "arm": arm, "config": f"configs/study1r_addon_D_b2/{name}.yaml",
                     "indices": list(range(N))})
    camp = {"name": GROUP, "stage": GROUP, "run_type": "confirmatory", "prereg_dir": "prereg_study1r",
            "freeze_lock": "prereg_study1r/FROZEN_1RD_B2.json", "n_per_arm": N, "indices": list(range(N)),
            "concurrency": 4, "order_seed": 20261025, "max_replacement_passes": 3,
            "budget": {"group": GROUP, "cap_usd": cap}, "arms": arms}
    (OUT / "campaign.yaml").write_text("# Study 1R-D fresh Cell B campaign. Runs only through "
                                       "`python -m sting.study1rd_b2 run`.\n" + yaml.safe_dump(camp, sort_keys=False),
                                       encoding="utf-8")
    print({"per_episode": per, "episodes": N * len(ARMS), "planned_usd": planned, "cap_usd": cap})


if __name__ == "__main__":
    main()
