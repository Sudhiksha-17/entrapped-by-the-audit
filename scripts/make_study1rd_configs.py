"""Generate the Study 1R-D configs (human message 86; prereg_study1r/AMENDMENT_1RD.md). Nothing is run.

screening: per candidate, a Silent screening config (the Study 1R mini-low Silent config with every LLM agent on the
           candidate, provider pinned, run_type exploratory, budget group study1r_addon_D_screening, cap $5) and an
           Offer-floor manipulation-check config (the Study 1R mini-low Offer config on the candidate).
campaign:  the confirmatory configs. Cell A (mini-low, gpt-4.1-mini): Offer-floor = configs/study1r/mini-low_offer.yaml,
           Silent-floor = configs/study1r_addon_C/mini-low_silent_floor.yaml, each with only stage, run name, budget
           and cost estimate changed; N = 60, indices 0-59. Cell B (optional, --cell-b MODEL_KEY --cell-b-cost USD):
           Silent, Silent-floor, Offer-floor on the chosen model, N = 33, indices 0-32.

Usage: python scripts/make_study1rd_configs.py screening
       python scripts/make_study1rd_configs.py campaign [--cell-b MODEL_KEY --cell-b-cost USD_PER_EPISODE]
"""
from __future__ import annotations

import argparse
import copy
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "configs" / "study1r_addon_D"
GROUP, SCREEN_GROUP = "study1r_addon_D", "study1r_addon_D_screening"
MARGIN, CAP_FACTOR = 1.10, 1.15
N_A, N_B = 60, 33
# Measured mean cost per completed episode, probe included (ledger): Study 1R mini-low Offer; Study 1R-C Silent-floor.
MEASURED_A = {"offer_floor": 0.2277, "silent_floor": 0.2248}
# Short keys keep run directory paths under the Windows path limit.
CANDIDATES = {  # OpenRouter model, pinned provider slug, $/M input, $/M output (OpenRouter endpoints, 2026-10-25)
    "kimi": ("moonshotai/kimi-k2-0905", "novita", 0.6, 2.5),
    "qwen": ("qwen/qwen3-235b-a22b-2507", "deepinfra", 0.09, 0.55),
    "gemini": ("google/gemini-2.5-flash-lite", "google-ai-studio", 0.1, 0.4),
}
# gpt-4.1-mini Silent episodes (Study 1R and Study 1R-C, 99 episodes): mean tokens per episode, probe included
TOKENS_IN, TOKENS_OUT = 357411, 51365


def est_cost(key: str) -> float:
    _, _, pi, po = CANDIDATES[key]
    return round(TOKENS_IN * pi / 1e6 + TOKENS_OUT * po / 1e6, 4)


def base(name: str) -> dict:
    return copy.deepcopy(yaml.safe_load((REPO / name).read_text(encoding="utf-8")))


def on_model(cfg: dict, key: str) -> dict:
    model, slug, _, _ = CANDIDATES[key]
    agent = {"provider": "openrouter", "model": model, "openrouter_provider": slug, "json_mode": True}
    cfg["sellers"] = [dict(agent) for _ in cfg["sellers"]]
    cfg["buyers"] = [dict(agent) for _ in cfg["buyers"]]
    return cfg


def finish(cfg: dict, stage: str, run_name: str, cost: float, group: str, cap: float, run_type: str) -> dict:
    cfg.update(stage=stage, run_name=run_name, run_type=run_type, estimated_cost_per_episode_usd=cost,
               budget={"group": group, "cap_usd": cap})
    return cfg


def write(path: Path, header: str, cfg: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")


def screening() -> None:
    d = OUT / "screening"
    for key in CANDIDATES:
        c = est_cost(key)
        s = finish(on_model(base("configs/study1r/mini-low_silent.yaml"), key), SCREEN_GROUP,
                   f"s1rd_scr_{key}_silent", round(c * MARGIN, 4), SCREEN_GROUP, 5.0, "exploratory")
        s["replicates"] = 3
        write(d / f"{key}_silent.yaml", "# Study 1R-D Cell B screening (exploratory; indices 1000+; never confirmatory). "
              "Generated by scripts/make_study1rd_configs.py.\n", s)
        o = finish(on_model(base("configs/study1r/mini-low_offer.yaml"), key), SCREEN_GROUP,
                   f"s1rd_scr_{key}_offer_check", round(c * MARGIN, 4), SCREEN_GROUP, 5.0, "exploratory")
        o["replicates"] = 1
        write(d / f"{key}_offer_check.yaml", "# Study 1R-D Cell B manipulation check (exploratory; index 1000+; "
              "prices not reported or used). Generated by scripts/make_study1rd_configs.py.\n", o)
        print(key, "estimated $/episode", c)


def campaign(cell_b: str | None, cell_b_cost: float | None) -> dict:
    per = {f"mini-low_{a}": round(MEASURED_A[a] * MARGIN, 4) for a in MEASURED_A}
    arms_spec = [("mini-low", "offer_floor", "configs/study1r/mini-low_offer.yaml", N_A, None),
                 ("mini-low", "silent_floor", "configs/study1r_addon_C/mini-low_silent_floor.yaml", N_A, None)]
    if cell_b:
        for arm, src in (("silent", "configs/study1r/mini-low_silent.yaml"),
                         ("silent_floor", "configs/study1r_addon_C/mini-low_silent_floor.yaml"),
                         ("offer_floor", "configs/study1r/mini-low_offer.yaml")):
            arms_spec.append((cell_b, arm, src, N_B, cell_b))
            per[f"{cell_b}_{arm}"] = round(cell_b_cost * MARGIN, 4)
    planned = sum(per[f"{c}_{a}"] * n for c, a, _, n, _ in arms_spec)
    cap = round(planned * CAP_FACTOR, 2)
    arms = []
    for cell, arm, src, n, model in arms_spec:
        name = f"{cell}_{arm}"
        cfg = base(src)
        if model:
            cfg = on_model(cfg, model)
        cfg = finish(cfg, GROUP, f"s1rd_{name}", per[name], GROUP, cap, "confirmatory")
        cfg["replicates"] = n
        if arm == "silent_floor":
            assert cfg["sting"]["x_rule"].get("silent_floor") is True and cfg["sting"]["condition"] == "silent"
        elif arm == "silent":
            assert cfg["sting"]["condition"] == "silent" and not cfg["sting"]["x_rule"].get("silent_floor")
        else:
            assert cfg["sting"]["condition"] == "offer"
        write(OUT / f"{name}.yaml", "# Study 1R-D arm (human message 86; prereg_study1r/AMENDMENT_1RD.md). Generated by "
              "scripts/make_study1rd_configs.py. Runs only through `python -m sting.study1rd run`.\n", cfg)
        arms.append({"name": name, "cell": cell, "arm": arm, "config": f"configs/study1r_addon_D/{name}.yaml",
                     "indices": list(range(n))})
    camp = {"name": GROUP, "stage": GROUP, "run_type": "confirmatory", "prereg_dir": "prereg_study1r",
            "freeze_lock": "prereg_study1r/FROZEN_1RD.json", "n_per_arm": N_A, "indices": list(range(N_A)),
            "concurrency": 4, "order_seed": 20261025, "max_replacement_passes": 3,
            "budget": {"group": GROUP, "cap_usd": cap}, "arms": arms}
    write(OUT / "campaign.yaml", "# Study 1R-D campaign. Runs only through `python -m sting.study1rd run`; NOT RUN until "
          "approved and frozen.\n", camp)
    plan = {"per_episode": per, "episodes": sum(n for *_, n, _ in arms_spec), "planned_usd": round(planned, 2),
            "cap_usd": cap}
    print(plan)
    return plan


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["screening", "campaign"])
    ap.add_argument("--cell-b", default=None, choices=sorted(CANDIDATES))
    ap.add_argument("--cell-b-cost", type=float, default=None)
    a = ap.parse_args()
    if a.what == "screening":
        screening()
    else:
        if bool(a.cell_b) != (a.cell_b_cost is not None):
            raise SystemExit("--cell-b and --cell-b-cost go together")
        campaign(a.cell_b, a.cell_b_cost)


if __name__ == "__main__":
    main()
